export function FileIcon({ className, name }: { className?: string; name: string }) {
  const extension = name.split(".").pop()?.toLowerCase() ?? ""
  // own keys alone, so a name ending .constructor or .__proto__ draws the plain file, not an inherited value
  const { bg, hue, icon } = Object.hasOwn(BY_EXTENSION, extension) ? BY_EXTENSION[extension] : PLAIN
  const paths: IconPath[] = ICONS[icon]
  return (
    <svg aria-hidden className={cn(HUES[hue], className)} fill="none" viewBox="0 0 16 16">
      {paths.map((path, index) => (
        <path
          key={index}
          className={path.bg && bg ? HUES[bg] : undefined}
          clipRule={path.evenodd ? "evenodd" : undefined}
          d={path.d}
          fill="currentColor"
          fillRule={path.evenodd ? "evenodd" : undefined}
          opacity={path.opacity}
        />
      ))}
    </svg>
  )
}
